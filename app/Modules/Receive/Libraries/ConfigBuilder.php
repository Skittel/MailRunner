<?php

namespace App\Modules\Receive\Libraries;

use CodeIgniter\Database\BaseConnection;

/**
 * Builds the files the receive mail path reads (Postfix maps, routes.json, credentials.json, postfix.conf) from the database.
 * Pure function of the DB state; writing and activating is done by ConfigApplier.
 */
class ConfigBuilder
{
    public function __construct(private readonly BaseConnection $db)
    {
    }

    /**
     * Role addresses (RFC 2142) accepted for every domain of every enabled project, regardless of the
     * recipient pattern. Their original mail is always kept; delivery per project setting role_mail.
     */
    public const ROLE_LOCALPARTS = ['postmaster', 'abuse'];

    /**
     * @return array<string, string> file name => content
     */
    public function build(): array
    {
        $rows = $this->db->query(
            'SELECT r.route_type, r.route, p.id AS project_id, p.project_key, p.profile, p.enabled,
                    p.recipient_pattern, p.recipient_always_allow, c.customer_key, c.enabled AS customer_enabled
             FROM receive_routes r
             JOIN projects p ON p.id = r.project_id
             JOIN customers c ON c.id = p.customer_id
             WHERE p.type = \'receive\'
             ORDER BY r.route',
        )->getResultArray();

        $domains = $mailboxes = $routes = [];
        $access  = [];
        $roleOwner = []; // domain of an address route -> route entry (for postmaster@/abuse@ of that domain)
        foreach ($rows as $row) {
            if (! (bool) $row['enabled'] || ! (bool) $row['customer_enabled']) {
                continue; // disabled: unknown recipient -> 550 at RCPT TO
            }
            $domain             = $row['route_type'] === 'domain' ? $row['route'] : substr($row['route'], strpos($row['route'], '@') + 1);
            $domains[$domain]   = true;
            $mailboxes[]        = ($row['route_type'] === 'domain' ? '@' . $row['route'] : $row['route']) . ' OK';
            $entry              = [
                'project_id' => (int) $row['project_id'],
                'project'    => $row['customer_key'] . '/' . $row['project_key'],
                'profile'    => $row['profile'],
            ];
            $routes[$row['route']] = $entry;
            if ($row['route_type'] === 'domain') {
                $alwaysAllow = array_values(array_unique(array_merge(self::ROLE_LOCALPARTS, json_decode($row['recipient_always_allow'] ?? '[]', true) ?: [])));
                if ($row['recipient_pattern'] !== null) {
                    $access[] = self::recipientRule($row['route'], $row['recipient_pattern'], $alwaysAllow);
                }
            } else {
                $roleOwner[$domain] ??= $entry;
            }
        }
        // domains that only have address routes: accept the role addresses for the project of the first one
        foreach ($roleOwner as $domain => $entry) {
            if (isset($routes[$domain])) {
                continue; // a domain route exists, it receives the role addresses
            }
            foreach (self::ROLE_LOCALPARTS as $local) {
                $addr = $local . '@' . $domain;
                if (! isset($routes[$addr])) {
                    $routes[$addr] = $entry;
                    $mailboxes[]   = $addr . ' OK';
                }
            }
        }
        ksort($routes);

        $header      = "# Generated by MailRunner (spark mr:apply). Do not edit.\n";
        $credentials = $this->credentials();
        $send        = $this->sendAccesses();
        foreach ($send['credentials'] as $user => $entry) {
            $credentials[$user] = $entry; // usernames are unique on the node across both roles
        }
        unset($send['credentials']);
        // AUTH without TLS on port 25 is offered only while at least one credential allows it (submission ports always need TLS)
        $plain = array_filter($credentials, static fn ($c) => ! $c['tls_required']) !== [];

        return [
            'domains'               => $header . implode('', array_map(static fn ($d) => $d . " OK\n", array_keys($domains))),
            'mailboxes'             => $header . implode('', array_map(static fn ($m) => $m . "\n", $mailboxes)),
            'recipient_access.pcre' => $header . implode("\n", $access) . "\n",
            'routes.json'           => json_encode(['routes' => (object) $routes, 'role_localparts' => self::ROLE_LOCALPARTS], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n",
            'credentials.json'      => json_encode(['credentials' => (object) $credentials], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n",
            'postfix.conf'          => $header . 'smtpd_tls_auth_only = ' . ($plain ? 'no' : 'yes') . "\n",
            'send.json'             => json_encode($send, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n",
            'send_clients.cidr'     => $header . implode('', array_map(static fn ($n) => $n['network'] . " OK\n", $send['ip_accesses'])),
        ];
    }

    /**
     * SMTP credentials the mail path accepts (mr-auth checks the password, mr-milter maps the login to the project):
     * enabled, not revoked, project and customer enabled. Contains Argon2id hashes only (file 0640 root:mailrunner).
     *
     * @return array<string, array<string, mixed>> username => entry
     */
    public function credentials(): array
    {
        $rows = $this->db->query(
            'SELECT s.*, p.project_key, p.profile, c.customer_key FROM smtp_credentials s
             JOIN projects p ON p.id = s.project_id JOIN customers c ON c.id = p.customer_id
             WHERE s.enabled = 1 AND s.revoked_at IS NULL AND s.scope = \'receive\' AND p.type = \'receive\' AND p.enabled = 1 AND c.enabled = 1 ORDER BY s.username',
        )->getResultArray();
        $out = [];
        foreach ($rows as $r) {
            $grace = $r['previous_password_hash'] !== null && $r['previous_valid_until'] !== null
                ? (new \DateTimeImmutable($r['previous_valid_until'], new \DateTimeZone('UTC')))->getTimestamp() : null;
            $out[$r['username']] = [
                'credential_id'        => $r['credential_id'],
                'project_id'           => (int) $r['project_id'],
                'project'              => $r['customer_key'] . '/' . $r['project_key'],
                'profile'              => $r['profile'],
                'hash'                 => $r['password_hash'],
                'previous_hash'        => $grace !== null ? $r['previous_password_hash'] : null,
                'previous_valid_until' => $grace,
                'tls_required'         => (bool) $r['tls_required'],
                'allowed_networks'     => $r['allowed_networks'] !== null ? json_decode($r['allowed_networks'], true) : null,
            ];
        }

        return $out;
    }

    /**
     * Send accesses for the mail path (E-27), only on nodes with the send role and only enabled accesses of enabled
     * profiles in enabled projects: SMTP logins (for mr-auth, scope "send"), client networks of ip accesses (Postfix
     * relay permission and mr-milter) and per access the profile rules mr-milter checks early (sender, recipients).
     * The final decision is made at end of data by `spark mr:send:accept`.
     *
     * @return array{credentials: array<string, array<string, mixed>>, accesses: object|array<string, array<string, mixed>>, ip_accesses: list<array{network: string, access_id: string}>}
     */
    public function sendAccesses(): array
    {
        $out = ['credentials' => [], 'accesses' => [], 'ip_accesses' => []];
        if (! config('Mailrunner')->sendEnabled) {
            $out['accesses'] = (object) [];

            return $out;
        }
        $rows = $this->db->query(
            'SELECT a.access_id, a.type, a.networks, a.project_id, pr.name AS profile_name, pr.senders, pr.recipients,
                    p.project_key, cu.customer_key, s.credential_id, s.username, s.password_hash, s.previous_password_hash, s.previous_valid_until,
                    s.tls_required, s.allowed_networks, s.enabled AS cred_enabled, s.revoked_at AS cred_revoked
             FROM send_accesses a JOIN send_profiles pr ON pr.id = a.profile_id JOIN projects p ON p.id = a.project_id
             JOIN customers cu ON cu.id = p.customer_id LEFT JOIN smtp_credentials s ON s.id = a.smtp_credential_id
             WHERE a.enabled = 1 AND pr.enabled = 1 AND p.enabled = 1 AND cu.enabled = 1 AND p.type = \'send\' AND a.type IN (\'smtp\', \'ip\')
             ORDER BY a.access_id',
        )->getResultArray();
        foreach ($rows as $r) {
            $project = $r['customer_key'] . '/' . $r['project_key'];
            $out['accesses'][$r['access_id']] = [
                'project_id' => (int) $r['project_id'], 'project' => $project, 'profile' => $r['profile_name'],
                'senders' => json_decode($r['senders'], true), 'recipients' => $r['recipients'] === null ? null : json_decode($r['recipients'], true),
            ];
            if ($r['type'] === 'ip') {
                foreach (json_decode((string) $r['networks'], true) ?: [] as $n) {
                    $out['ip_accesses'][] = ['network' => $n, 'access_id' => $r['access_id']];
                }
            } elseif ($r['username'] !== null && (int) $r['cred_enabled'] === 1 && $r['cred_revoked'] === null) {
                $grace = $r['previous_password_hash'] !== null && $r['previous_valid_until'] !== null
                    ? (new \DateTimeImmutable($r['previous_valid_until'], new \DateTimeZone('UTC')))->getTimestamp() : null;
                $out['credentials'][$r['username']] = [
                    'scope' => 'send', 'access_id' => $r['access_id'], 'credential_id' => $r['credential_id'],
                    'project_id' => (int) $r['project_id'], 'project' => $project, 'profile' => 'smarthost',
                    'hash' => $r['password_hash'], 'previous_hash' => $grace !== null ? $r['previous_password_hash'] : null,
                    'previous_valid_until' => $grace, 'tls_required' => (bool) $r['tls_required'],
                    'allowed_networks' => $r['allowed_networks'] !== null ? json_decode($r['allowed_networks'], true) : null,
                ];
            }
        }
        if ($out['accesses'] === []) {
            $out['accesses'] = (object) [];
        }

        return $out;
    }

    /**
     * Postfix PCRE block: inside the domain, local parts must fully match the project pattern,
     * except the always-allowed ones. Leading ^ and trailing $ of the pattern are optional.
     *
     * @param list<string> $alwaysAllow
     */
    public static function recipientRule(string $domain, string $pattern, array $alwaysAllow): string
    {
        $pattern = preg_replace('/^\^|\$$/', '', $pattern);
        $pattern = str_replace('/', '\/', (string) $pattern);
        $lines   = ['if /@' . preg_quote($domain, '/') . '$/'];
        if ($alwaysAllow !== []) {
            $lines[] = '/^(?:' . implode('|', array_map(static fn ($l) => preg_quote($l, '/'), $alwaysAllow)) . ')@/ DUNNO';
        }
        $lines[] = '!/^(?:' . $pattern . ')@/ 550 5.1.1 User unknown';
        $lines[] = 'endif';

        return implode("\n", $lines);
    }
}
