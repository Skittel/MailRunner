"""Send role in mr-milter (decision E-27): which session is a submission, early checks, hand-off to PHP.

Order of decision per transaction: (1) SMTP AUTH with a send login (credentials.json, scope "send");
(2) no login and the client address inside an ip send access (send.json); (3) otherwise normal receive.

Early checks (from send.json, generated by `spark mr:apply`): the envelope sender and every recipient against the
profile. The final decision (header From, DKIM domain, limits) and the encrypted queueing happen at end of data in
`spark mr:send:accept`, the same code as POST /v1/send. The milter then answers DISCARD (Postfix confirms with 250
and drops its copy) or the code from PHP; Postfix itself never delivers a submission.
"""
import base64
import ipaddress
import json
import os
import subprocess

from . import config

SEND_FILE = os.path.join(config.CONFIG_DIR, "generated", "current", "send.json")
PHP = os.environ.get("MR_PHP", "/usr/bin/php")
SPARK = os.environ.get("MR_SPARK", "/opt/mailrunner/current/spark")
ACCEPT_TIMEOUT = float(os.environ.get("MR_SEND_ACCEPT_TIMEOUT", "60"))
MAX_RECIPIENTS = 100   # SendSubmissionService::MAX_RECIPIENTS


class SendConfig:
    """send.json, reloaded when the file (or the "current" symlink target) changes."""

    def __init__(self, path=SEND_FILE):
        self.path = path
        self.stamp = None
        self.accesses = {}
        self.networks = []   # (ip_network, access_id)

    def _load(self):
        try:
            stamp = (os.stat(self.path).st_mtime_ns, os.path.realpath(self.path))
        except FileNotFoundError:
            self.stamp, self.accesses, self.networks = None, {}, []
            return
        if stamp == self.stamp:
            return
        with open(self.path) as fh:
            data = json.load(fh)
        self.accesses = data.get("accesses") or {}
        nets = []
        for entry in data.get("ip_accesses") or []:
            try:
                nets.append((ipaddress.ip_network(entry["network"], strict=False), entry["access_id"]))
            except (KeyError, ValueError):
                continue
        self.networks = nets
        self.stamp = stamp

    def access(self, access_id):
        self._load()
        return self.accesses.get(access_id)

    def access_for_ip(self, client_ip):
        """access_id of the ip access the client address belongs to, or None."""
        self._load()
        try:
            ip = ipaddress.ip_address(client_ip)
        except ValueError:
            return None
        if ip.version == 6 and ip.ipv4_mapped:
            ip = ip.ipv4_mapped
        for net, access_id in self.networks:
            if ip.version == net.version and ip in net:
                return access_id
        return None


def domain_of(address):
    return address.rsplit("@", 1)[1] if "@" in address else address


def matches(entries, address):
    """Exact address or exact domain, case-insensitive (SendSubmissionService::matches)."""
    a = (address or "").strip().lower()
    return a in entries or domain_of(a) in entries


def check_sender(rules, mail_from):
    """None if the envelope sender is allowed by the profile, else an SMTP reply (code, enhanced, text)."""
    if not mail_from or "@" not in mail_from:
        return ("550", "5.7.1", "A sender address is required for relaying")
    if not matches(rules.get("senders") or [], mail_from):
        return ("550", "5.7.1", f"Sender not allowed by profile {rules.get('profile', '')}")
    return None


def check_recipient(rules, rcpt, count):
    """None if the recipient may be added (count = recipients accepted so far), else an SMTP reply."""
    if count >= MAX_RECIPIENTS:
        return ("452", "4.5.3", "Too many recipients for this transaction")
    allowed = rules.get("recipients")
    if allowed is not None and not matches(allowed, rcpt):
        return ("550", "5.7.1", f"Recipient not allowed by profile {rules.get('profile', '')}")
    return None


def accept(handoff, run=subprocess.run):
    """Hands one submission to `spark mr:send:accept`. Returns the parsed answer; a local failure becomes 451."""
    payload = json.dumps(dict(handoff, raw_b64=base64.b64encode(handoff.pop("raw")).decode())).encode()
    try:
        proc = run([PHP, SPARK, "--no-header", "mr:send:accept"], input=payload, capture_output=True, timeout=ACCEPT_TIMEOUT)
        out = proc.stdout.decode("utf-8", "replace")
        answer = json.loads(out[out.index("{"):].splitlines()[0])
    except (subprocess.TimeoutExpired, OSError, ValueError) as e:
        return {"ok": False, "code": "451", "enhanced": "4.3.0", "error": "HANDOFF_FAILED",
                "message": "Temporary local problem, please try again later", "detail": e.__class__.__name__}
    if not isinstance(answer, dict) or "ok" not in answer:
        return {"ok": False, "code": "451", "enhanced": "4.3.0", "error": "HANDOFF_FAILED", "message": "Temporary local problem, please try again later"}
    return answer


def smtp_text(message):
    """Reply text safe for an SMTP line (printable ASCII, no CR/LF), at most 200 characters."""
    return "".join(ch if 32 <= ord(ch) < 127 else "?" for ch in (message or ""))[:200] or "Rejected"
