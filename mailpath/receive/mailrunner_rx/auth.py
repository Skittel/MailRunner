"""SMTP AUTH for Postfix: a small server speaking the Dovecot auth protocol (smtpd_sasl_type = dovecot).

Postfix connects to 127.0.0.1:8897 (smtpd_sasl_path) and asks for PLAIN or LOGIN. Credentials come from
credentials.json (generated by `spark mr:apply` from smtp_credentials: Argon2id hashes, project, TLS rule,
allowed networks); the file is re-read when it changes, so revocations apply within seconds.

Rules per login:
  - the password matches the current hash, or the previous one during a rotation grace period,
  - without TLS (port 25 only; submission ports require TLS in Postfix) only if the credential allows it,
  - the client address is inside allowed_networks if the credential has a list,
  - after FAIL_LIMIT failures from one address within FAIL_WINDOW s the address is refused for BLOCK_SECONDS.
Failures are logged with address and username (fail2ban), never the password.
"""
import base64
import ipaddress
import json
import os
import time

import nacl.exceptions
import nacl.pwhash

FAIL_LIMIT = 5
FAIL_WINDOW = 600
BLOCK_SECONDS = 900


class Credentials:
    """credentials.json, reloaded when the file (or the "current" symlink target) changes."""

    def __init__(self, path):
        self.path = path
        self.stamp = None
        self.entries = {}

    def get(self, username):
        try:
            stamp = (os.stat(self.path).st_mtime_ns, os.path.realpath(self.path))
        except FileNotFoundError:
            self.entries, self.stamp = {}, None
            return None
        if stamp != self.stamp:
            with open(self.path) as fh:
                self.entries = {k.lower(): v for k, v in (json.load(fh).get("credentials") or {}).items()}
            self.stamp = stamp
        return self.entries.get((username or "").strip().lower())


class Limiter:
    """Failed logins per client address (in memory)."""

    def __init__(self, now=time.monotonic):
        self.now = now
        self.fails = {}     # ip -> [timestamps]
        self.blocked = {}   # ip -> until

    def is_blocked(self, ip):
        until = self.blocked.get(ip)
        if until is None:
            return False
        if self.now() >= until:
            del self.blocked[ip]
            return False
        return True

    def failed(self, ip):
        t = self.now()
        recent = [x for x in self.fails.get(ip, []) if t - x < FAIL_WINDOW] + [t]
        self.fails[ip] = recent
        if len(recent) >= FAIL_LIMIT:
            self.blocked[ip] = t + BLOCK_SECONDS
            self.fails.pop(ip, None)
        if len(self.fails) > 100_000:   # bound memory under a distributed attack
            self.fails.clear()

    def succeeded(self, ip):
        self.fails.pop(ip, None)


def verify_hash(stored, password):
    if not stored:
        return False
    try:
        return nacl.pwhash.verify(stored.encode(), password.encode())
    except (nacl.exceptions.InvalidkeyError, nacl.exceptions.CryptoError, ValueError):
        return False


def check_login(entry, password, secured, client_ip, now=None):
    """Returns None if the login is allowed, else the reason (for the log)."""
    if entry is None:
        return "unknown user"
    if not secured and entry.get("tls_required", True):
        return "TLS required"
    nets = entry.get("allowed_networks")
    if nets:
        try:
            ip = ipaddress.ip_address(client_ip)
            if not any(ip in ipaddress.ip_network(n, strict=False) for n in nets):
                return "network not allowed"
        except ValueError:
            return "network not allowed"
    if verify_hash(entry.get("hash"), password):
        return None
    until = entry.get("previous_valid_until")
    if entry.get("previous_hash") and until and (now or time.time()) < until and verify_hash(entry["previous_hash"], password):
        return None
    return "wrong password"


def decode_plain(resp):
    """PLAIN initial response -> (username, password) or None. authzid must be empty or equal to authcid."""
    try:
        parts = base64.b64decode(resp, validate=True).decode("utf-8").split("\0")
    except (ValueError, UnicodeDecodeError):
        return None
    if len(parts) != 3 or not parts[1] or (parts[0] and parts[0] != parts[1]):
        return None
    return parts[1], parts[2]


def b64(text):
    return base64.b64encode(text.encode()).decode()


def unb64(data):
    try:
        return base64.b64decode(data, validate=True).decode("utf-8")
    except (ValueError, UnicodeDecodeError):
        return None


def handshake(pid, cuid, cookie):
    return (f"VERSION\t1\t2\nMECH\tPLAIN\tplaintext\nMECH\tLOGIN\tplaintext\nSPID\t{pid}\nCUID\t{cuid}\n"
            f"COOKIE\t{cookie}\nDONE\n")


def parse_auth(fields):
    """AUTH\t<id>\t<mech>\t<key=value or flag>... -> (id, mech, params)."""
    params = {}
    for f in fields[3:]:
        k, _, v = f.partition("=")
        params[k] = v if _ else True
    return fields[1], fields[2].upper(), params


def escape(value):
    return value.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n")
