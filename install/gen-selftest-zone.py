#!/usr/bin/python3 -I
"""Writes the unbound configuration of the local self test zone "selftest.test" (RFC 2606, never on the Internet).

  gen-selftest-zone.py <hostname> <output file>

Self test mails (mr:selftest) are sent from the node's own public addresses to itself. The zone holds the
sender domains of the scenarios: SPF allows the node's addresses, DKIM keys are the public parts of the
test keys in mailpath/vendor/smartmailflow/tests/keys. Each subdomain is one fixed case.
unbound answers local-data directly (no DNSSEC validation, no extra name server).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "mailpath", "vendor", "smartmailflow", "tests"))
from mailtools import dkim_record  # noqa: E402

ZONE = "selftest.test"


def own_addresses(hostname):
    """A and AAAA of the node name from the node resolver (getaddrinfo may hide IPv6)."""
    import dns.resolver
    r = dns.resolver.Resolver(configure=False)
    r.nameservers = ["127.0.0.1"]
    out = []
    for rtype in ("A", "AAAA"):
        try:
            out.append(sorted(a.to_text() for a in r.resolve(hostname, rtype)))
        except (dns.resolver.NoAnswer, dns.resolver.NXDOMAIN):
            out.append([])
    return out[0], out[1]


def txt(value):
    parts = [value[i:i + 255] for i in range(0, len(value), 255)] or [""]
    return " ".join(f'"{p}"' for p in parts)


def main():
    hostname, out = sys.argv[1], sys.argv[2]
    v4, v6 = own_addresses(hostname)
    if not v4:
        sys.exit(f"no IPv4 address for {hostname}")
    spf_ok = "v=spf1 " + " ".join([f"ip4:{a}" for a in v4] + [f"ip6:{a}" for a in v6]) + " -all"
    rr = []

    def add(name, rtype, data):
        fqdn = f"{name}.{ZONE}." if name != "@" else f"{ZONE}."
        rr.append(f"    local-data: '{fqdn} 60 IN {rtype} {data}'")

    add("@", "SOA", f"ns.{ZONE}. hostmaster.{ZONE}. 1 3600 600 86400 60")
    # HELO name of the self test client -> node addresses (HELO check pass; SPF for the null sender)
    for a in v4:
        add("client", "A", a)
    for a in v6:
        add("client", "AAAA", a)
    add("client", "TXT", txt(spf_ok))
    # recipient domain (route of project system/selftest)
    add("rx", "MX", f"10 {hostname}.")
    # pass: SPF ok, DKIM keys, DMARC reject, Return-Path with MX
    add("pass", "TXT", txt(spf_ok))
    add("pass", "MX", f"10 mx.pass.{ZONE}.")
    add("mx.pass", "A", "192.0.2.25")
    add("mx.pass", "AAAA", "2001:db8::25")
    add("_dmarc.pass", "TXT", txt("v=DMARC1; p=reject"))
    add("s2048._domainkey.pass", "TXT", txt(dkim_record("s2048.key")))
    add("ed25519._domainkey.pass", "TXT", txt(dkim_record("ed25519.key")))
    # spffail: SPF -all, DMARC reject -> spf fail, dmarc fail
    add("spffail", "TXT", txt("v=spf1 -all"))
    add("spffail", "MX", f"10 mx.pass.{ZONE}.")
    add("_dmarc.spffail", "TXT", txt("v=DMARC1; p=reject"))

    body = "\n".join([
        f"# GENERATED by install/gen-selftest-zone.py for {hostname} - do not edit.",
        f"# Local self test zone {ZONE} (mr:selftest). Exists only on this node.",
        "server:",
        f'    local-zone: "{ZONE}." static',
        *rr,
    ]) + "\n"
    tmp = out + ".tmp"
    with open(tmp, "w") as fh:
        fh.write(body)
    os.replace(tmp, out)
    print(f"{out}: {len(rr)} records, IPv4 {len(v4)}, IPv6 {len(v6)}")


if __name__ == "__main__":
    main()
